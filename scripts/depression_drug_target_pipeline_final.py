    class DrugTargetGCN(nn.Module):

        def __init__(
            self,
            protein_input_dim=20,
            hidden_dim=128,
            drug_input_dim=1024,
            num_classes=2,
        ):

            super().__init__()

            self.conv1 = GCNConv(protein_input_dim, hidden_dim)

            self.conv2 = GCNConv(hidden_dim, hidden_dim)

            self.drug_layer = nn.Linear(drug_input_dim, hidden_dim)

            self.classifier = nn.Sequential(
                nn.Linear(hidden_dim * 2, hidden_dim),
                nn.ReLU(),
                nn.Dropout(0.2),
                nn.Linear(hidden_dim, num_classes),
            )

        def forward(self, x, edge_index, drug_features):

            x = self.conv1(x, edge_index)

            x = torch.relu(x)

            x = self.conv2(x, edge_index)

            x = torch.relu(x)

            protein_representation = torch.mean(x, dim=0, keepdim=True)

            drug_representation = self.drug_layer(drug_features)

            combined = torch.cat(
                [
                    protein_representation,
                    drug_representation,
                ],
                dim=1,
            )

            return self.classifier(combined)

