"""
Depression Drug-Target Prediction Pipeline
==========================================

This script provides a reproducible Python implementation of the
computational workflow developed for the dissertation project on
identifying and prioritising potential drug-target interactions
associated with depression.

The workflow is organised into the following stages:

1. Depression-associated gene analysis
2. Protein characterisation
3. Drug-target interaction analysis
4. Baseline Random Forest modelling
5. Protein embedding generation using ESM-2
6. Feature integration
6A. AlphaFold protein structure preparation
7. Graph Neural Network development
8. Novel drug-target prediction
9. Molecular docking validation
10. Model explainability and final candidate interpretation

The stages process the project datasets, generate derived features, train
and evaluate machine-learning models, identify candidate drug-target
pairs, perform molecular docking validation, and produce figures and
tabular outputs for subsequent analysis and reporting.

Each stage is implemented as a separate function so that the complete
workflow can be executed sequentially or individual stages can be
re-run when required.

Project structure
-----------------
The script is stored in the ``scripts`` directory of the project
repository and uses the following directory structure:

    project_root/
        data/
            raw/
            processed/
        figures/
        models/
        results/
        docking/
        notebooks/
        scripts/

The raw data directory may contain the primary input datasets, structure
metadata, missing-structure information, and the protein structure files
used during structure preparation.

Reproducibility
---------------
A fixed random seed is used where applicable. Intermediate datasets,
trained models, figures, docking outputs, and analysis results are saved
to the project directory for subsequent stages and reporting.

The project root can be specified using the ``DEPRESSION_PROJECT_ROOT``
environment variable. When the variable is not set, the repository root
is derived from the location of this script.

Usage
-----
From the project repository root, run the complete workflow with:

    python scripts/depression_drug_target_pipeline.py --stage all

Individual stages can be executed using their stage identifiers, for
example:

    python scripts/depression_drug_target_pipeline.py --stage 01
    python scripts/depression_drug_target_pipeline.py --stage 07

Stages should normally be executed in numerical order on the first run,
as later stages use outputs generated by earlier stages.

External software and specialised Python packages are required for some
stages, particularly protein embedding generation, graph neural network
modelling, molecular docking, and structural visualisation.
"""

