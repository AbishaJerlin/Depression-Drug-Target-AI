def stage_08_novel_drug_target_prediction():
    """Apply the trained GNN to all interaction samples to rank candidates."""
    _ensure_package("torch")
    _ensure_package("torch_geometric")

    import torch

    _ensure_directories(RESULTS_PATH, FIGURE_PATH)

    _set_seeds(SEED)
    print("Random seed set to:", SEED)

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    print("Running device:", device)

    gnn_model_file = os.path.join(MODEL_PATH, "drug_target_gnn_model.pth")
    print("Model path:", MODEL_PATH)
    print("Model directory exists:", os.path.exists(MODEL_PATH))
    if os.path.exists(MODEL_PATH):
        print("Files inside models folder:")
        for file in os.listdir(MODEL_PATH):
            print(file)
    print("Expected model file:")
    print(gnn_model_file)
    print("Model file exists:", os.path.exists(gnn_model_file))

    model = DrugTargetGNN_Stage07.build(node_features=20, drug_features=1024, hidden_dim=128).to(
        device
    )
    model.load_state_dict(torch.load(gnn_model_file, map_location=device))
    model.eval()
    print("Trained GNN weights loaded successfully.")

    graph_data_path = os.path.join(PROCESSED_DATA_PATH, "protein_graphs.pkl")
    print("Loading protein graph data...")
    with open(graph_data_path, "rb") as file:
        protein_graphs = pickle.load(file)
    print("Protein graphs loaded successfully.")
    print("Number of protein graphs:", len(protein_graphs))

    interaction_data_path = os.path.join(PROCESSED_DATA_PATH, "clean_drug_target_interactions.pkl")
    print("Loading drug-target interaction data...")
    interactions_df = pd.read_pickle(interaction_data_path)
    print("Drug-target interaction data loaded successfully.")
    print("Number of interaction records:", len(interactions_df))
    print("Columns:")
    print(interactions_df.columns.tolist())

    print("Checking drug fingerprint features...")
    fingerprint_lengths = interactions_df["fingerprint"].apply(len)
    print("Fingerprint length:", fingerprint_lengths.unique())
    print("Number of fingerprint features:", fingerprint_lengths.iloc[0])

    print("Creating protein graph lookup...")
    protein_graph_lookup = {g.uniprot_id: g for g in protein_graphs}
    print("Protein graph lookup created.")
    print("Available protein graphs:", len(protein_graph_lookup))

    prediction_samples = []
    missing_graphs = 0
    for _, row in interactions_df.iterrows():
        uniprot_id = row["uniprot_id"]
        if uniprot_id not in protein_graph_lookup:
            missing_graphs += 1
            continue
        graph = protein_graph_lookup[uniprot_id]
        sample = graph.clone()
        sample.drug_features = torch.tensor(row["fingerprint"], dtype=torch.float32).unsqueeze(0)
        sample.uniprot_id = uniprot_id
        sample.drug_chembl_id = row["drug_chembl_id"]
        sample.active = int(row["active"])
        prediction_samples.append(sample)

    print("\nPrediction samples prepared successfully.")
    print("Total prediction samples:", len(prediction_samples))
    print("Missing protein graphs:", missing_graphs)

    from torch_geometric.loader import DataLoader

    print("Generating GNN predictions...")
    model.eval()
    prediction_loader = DataLoader(prediction_samples, batch_size=32, shuffle=False)

    all_predictions, all_probabilities = [], []
    all_labels, all_uniprot_ids, all_drug_ids = [], [], []

    with torch.no_grad():
        for batch in prediction_loader:
            batch = batch.to(device)
            output = model(batch.x, batch.edge_index, batch.batch, batch.drug_features)
            probabilities = torch.softmax(output, dim=1)
            predictions = torch.argmax(probabilities, dim=1)
            all_predictions.extend(predictions.cpu().numpy())
            all_probabilities.extend(probabilities[:, 1].cpu().numpy())
            all_labels.extend(batch.active.cpu().numpy())
            all_uniprot_ids.extend(batch.uniprot_id)
            all_drug_ids.extend(batch.drug_chembl_id)

    print("Prediction generation completed.")
    print("Total predictions:", len(all_predictions))

    prediction_results = pd.DataFrame(
        {
            "uniprot_id": all_uniprot_ids,
            "drug_chembl_id": all_drug_ids,
            "true_label": all_labels,
            "predicted_label": all_predictions,
            "prediction_probability": all_probabilities,
        }
    )
    print("Prediction results dataframe created successfully.")
    print("Number of prediction records:", len(prediction_results))
    print(prediction_results.head())

    ranked_predictions = prediction_results.sort_values(
        by="prediction_probability", ascending=False
    )
    print("Candidate interactions ranked successfully.")
    print("Top 10 predicted drug-target interactions:")
    print(ranked_predictions.head(10))

    # Stage 08 is used for candidate prediction and ranking.
    # Independent model performance is reported from Stage 07,
    # which evaluates the trained GNN on the held-out test set.
    print("\nStage 08 prediction and ranking completed.")
    print("Model performance should be interpreted from Stage 07 held-out evaluation.")

    prediction_output_path = os.path.join(RESULTS_PATH, "gnn_prediction_results.csv")
    prediction_results.to_csv(prediction_output_path, index=False)
    print("Prediction results saved successfully.")
    print("Saved file:", prediction_output_path)

    ranked_predictions_path = os.path.join(RESULTS_PATH, "gnn_ranked_candidate_predictions.csv")
    ranked_predictions.to_csv(ranked_predictions_path, index=False)
    print("Ranked candidate predictions saved successfully.")
    print("Saved file:", ranked_predictions_path)

    return ranked_predictions


