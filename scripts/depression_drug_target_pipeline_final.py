def _ensure_directories(*paths):
    """Create required output directories when they are absent."""
    for path in paths:
        os.makedirs(path, exist_ok=True)


def _ensure_package(module_name, pip_name=None):
    """Check that a required package is available before a stage runs.

    Packages are not installed automatically at runtime. A clear installation
    instruction is provided when a required dependency is unavailable.
    """
    pip_name = pip_name or module_name
    try:
        __import__(module_name)
    except ImportError as exc:
        raise ImportError(
            f"Required package '{module_name}' is not installed. "
            f"Install it first, e.g.:  pip install {pip_name}"
        ) from exc


def _set_seeds(seed=SEED):
    random.seed(seed)
    np.random.seed(seed)
    try:
        import torch

        torch.manual_seed(seed)
        if torch.cuda.is_available():
            torch.cuda.manual_seed(seed)
            torch.cuda.manual_seed_all(seed)
    except ImportError:
        pass


