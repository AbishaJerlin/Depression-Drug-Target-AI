# Canonical run order. Note 06A only needs to run once before stage 07 (it
# does not depend on stage 06's output, matching the original notebooks).
STAGE_ORDER = ["01", "02", "03", "04", "05", "06", "06A", "07", "08", "09", "10"]


def _print_banner(stage_key, description):
    print("\n" + "=" * 78)
    print(f"STAGE {stage_key}: {description}")
    print("=" * 78 + "\n")


def run_stage(stage_key):
    description, func = STAGES[stage_key]
    _print_banner(stage_key, description)
    return func()


def main():
    import argparse

    parser = argparse.ArgumentParser(
        description=(
            "Depression Drug-Target Prediction Pipeline - " "reproducible computational workflow."
        )
    )
    parser.add_argument(
        "--stage",
        default="all",
        choices=["all"] + STAGE_ORDER,
        help=(
            "Which stage to run. 'all' runs every stage once, in the same "
            "order the notebooks were designed to be run (01 -> 10). "
            "Default: all."
        ),
    )
    args = parser.parse_args()

    print(f"PROJECT_ROOT = {PROJECT_ROOT}")
