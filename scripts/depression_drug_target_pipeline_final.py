# STAGE 05 - Notebook 05: Protein Embedding Generation (ESM-2)
# ---------------------------------------------------------------------------
def stage_05_protein_embedding_generation():
    """Generate ESM-2 protein embeddings and visualise with PCA."""
    _ensure_package("torch")
    _ensure_package("transformers")
    import torch
    from sklearn.decomposition import PCA
    from tqdm.auto import tqdm

    _ensure_directories(PROCESSED_DATA_PATH, FIGURE_PATH, MODEL_PATH, RESULTS_PATH)

    protein_data = pd.read_csv(os.path.join(PROCESSED_DATA_PATH, "protein_cleaned.csv"))
    print("Protein dataset loaded successfully.")

    print("Dataset Shape:")
    print(protein_data.shape)
    print("\nColumn Names:")
    print(protein_data.columns.tolist())
    print("\nFirst Five Records:")
    print(protein_data.head())

    print("Missing Values:")
    print(protein_data.isnull().sum())
    print("\nDuplicate Records:")
    print(protein_data.duplicated().sum())
    print("\nSequence Length Statistics:")
    print(protein_data["length"].describe())

    from transformers import AutoTokenizer, EsmModel

    MODEL_NAME = "facebook/esm2_t6_8M_UR50D"
    print("Loading pretrained ESM-2 model...")
    tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)
    esm_model = EsmModel.from_pretrained(MODEL_NAME)

    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    esm_model.to(device)
    esm_model.eval()

    print("Model loaded successfully.\n")
    print(f"Model Name: {MODEL_NAME}")
    print(f"Device: {device}")
    print(f"Embedding Dimension: {esm_model.config.hidden_size}")
    print(f"Maximum Sequence Length: {tokenizer.model_max_length}")

    MAX_LENGTH = 1024
    print(f"Maximum protein sequence length used: {MAX_LENGTH}")

    def generate_embedding(sequence):
        """Generate ESM-2 embedding for a single protein sequence."""
        inputs = tokenizer(sequence, return_tensors="pt", truncation=True, max_length=MAX_LENGTH)
        inputs = {key: value.to(device) for key, value in inputs.items()}
        with torch.no_grad():
            outputs = esm_model(**inputs)
        # Mean pooling across sequence tokens
        embedding = outputs.last_hidden_state.mean(dim=1)
        return embedding.cpu().numpy().flatten()

    protein_embeddings = []
    protein_ids = []
    print("Generating protein embeddings...")
    for _, row in tqdm(protein_data.iterrows(), total=len(protein_data)):
        sequence = row["sequence"]
        embedding = generate_embedding(sequence)
        protein_embeddings.append(embedding)
        protein_ids.append(row["uniprot_id"])
    print("\nProtein embedding generation completed.")

    protein_embeddings = np.array(protein_embeddings)
    print("Embedding Shape:", protein_embeddings.shape)

    embedding_metadata = protein_data[["ensembl_id", "uniprot_id", "protein_name", "length"]].copy()
    embedding_metadata["embedding_index"] = range(len(embedding_metadata))
    print(embedding_metadata.head())

    print("Checking missing values...")
    print(np.isnan(protein_embeddings).sum())

    print("Number of proteins:", protein_embeddings.shape[0])
    print("Embedding features:", protein_embeddings.shape[1])

    embedding_statistics = pd.DataFrame(protein_embeddings)
    print(embedding_statistics.describe())

    print("Starting PCA analysis of protein embeddings...")
    pca = PCA(n_components=2, random_state=42)
    protein_embeddings_2d = pca.fit_transform(protein_embeddings)
    print("PCA transformation completed successfully.")

    print("Original embedding dimensions:", protein_embeddings.shape[1])
    print("Reduced dimensions:", protein_embeddings_2d.shape[1])

    pca_results = pd.DataFrame(protein_embeddings_2d, columns=["PC1", "PC2"])
    pca_results["uniprot_id"] = protein_ids
    print(pca_results.head())

    explained_variance = pca.explained_variance_ratio_
    print("Explained variance by PC1:", round(explained_variance[0] * 100, 2), "%")
    print("Explained variance by PC2:", round(explained_variance[1] * 100, 2), "%")
    print(
        "Total explained variance:",
        round(explained_variance.sum() * 100, 2),
        "%",
    )

    plt.figure(figsize=(10, 7))
    plt.scatter(pca_results["PC1"], pca_results["PC2"], alpha=0.7)
    plt.title("PCA Visualisation of ESM-2 Protein Embeddings")
    plt.xlabel("Principal Component 1")
    plt.ylabel("Principal Component 2")
    plt.tight_layout()
    plt.savefig(
        os.path.join(FIGURE_PATH, "protein_embeddings_pca.png"),
        dpi=300,
        bbox_inches="tight",
    )
    plt.close()

