# STAGE 03 - Notebook 03: Drug-Target Interaction Analysis
# ---------------------------------------------------------------------------
def stage_03_drug_target_interaction_analysis():
    """Clean interactions, compute pChEMBL/activity labels, Morgan fingerprints."""
    _ensure_package("rdkit", "rdkit")
    from rdkit import Chem
    from rdkit.Chem import AllChem

    _ensure_directories(PROCESSED_DATA_PATH, FIGURE_PATH)

    interaction_file = os.path.join(RAW_DATA_PATH, "drug_target_interactions.csv")
    interactions_df = pd.read_csv(interaction_file)

    print("Drug-target interaction dataset loaded successfully.")
    print(f"Number of interaction records: {interactions_df.shape[0]}")
    print(f"Number of features: {interactions_df.shape[1]}")

    print(interactions_df.head())
    interactions_df.info()
    print(interactions_df.describe(include="all"))

    missing_values = interactions_df.isnull().sum().sort_values(ascending=False)
    print(missing_values)

    plt.figure(figsize=(10, 5))
    missing_values.plot(kind="bar")
    plt.title("Missing Values in Drug\u2013Target Interaction Dataset")
    plt.xlabel("Features")
    plt.ylabel("Missing Values")
    plt.tight_layout()
    plt.savefig(os.path.join(FIGURE_PATH, "interaction_missing_values.png"), dpi=300)
    plt.close()

    duplicates = interactions_df.duplicated().sum()
    print(f"Duplicate records: {duplicates}")

    print(interactions_df["standard_type"].value_counts())

    plt.figure(figsize=(8, 5))
    sns.countplot(data=interactions_df, x="standard_type")
    plt.xticks(rotation=45)
    plt.title("Distribution of Binding Measurement Types")
    plt.tight_layout()
    plt.savefig(os.path.join(FIGURE_PATH, "binding_measurement_types.png"), dpi=300)
    plt.close()

    # Step A - clean
    clean_df = interactions_df.copy()
    clean_df = clean_df[clean_df["standard_units"] == "nM"]
    clean_df = clean_df.dropna(subset=["smiles", "standard_value"])
    clean_df = clean_df.drop_duplicates(subset=["uniprot_id", "smiles"])
    print(f"Remaining records: {len(clean_df)}")

    # Step B - pChEMBL + activity label
    clean_df["pchembl"] = -np.log10(clean_df["standard_value"] * 1e-9)
    print(clean_df[["drug_name", "standard_value", "pchembl"]].head())

    clean_df["active"] = (clean_df["pchembl"] >= 6).astype(int)
    print(clean_df["active"].value_counts())

    plt.figure(figsize=(5, 5))
    clean_df["active"].value_counts().plot(kind="bar")
    plt.title("Distribution of Active and Inactive Interactions")
    plt.xlabel("Activity Label")
    plt.ylabel("Number of Interactions")
    plt.tight_layout()
    plt.savefig(os.path.join(FIGURE_PATH, "activity_label_distribution.png"), dpi=300)
    plt.close()

    # Step C - Morgan fingerprints (1024-bit)
    def smiles_to_fp(smiles):
        molecule = Chem.MolFromSmiles(smiles)
        if molecule is None:
            return None
        return list(AllChem.GetMorganFingerprintAsBitVect(molecule, radius=2, nBits=1024))

    clean_df["fingerprint"] = clean_df["smiles"].apply(smiles_to_fp)
    clean_df = clean_df.dropna(subset=["fingerprint"])
    print("Morgan fingerprints generated successfully.")

    print(clean_df[["drug_name", "fingerprint"]].head())
    print(type(clean_df["fingerprint"].iloc[0]))
    print(len(clean_df["fingerprint"].iloc[0]))

    processed_interactions = os.path.join(PROCESSED_DATA_PATH, "clean_drug_target_interactions.pkl")
    clean_df.to_pickle(processed_interactions)
    print("Processed interaction dataset saved successfully.")

    return clean_df


