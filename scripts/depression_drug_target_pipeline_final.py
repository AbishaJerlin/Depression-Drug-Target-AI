def _create_protein_graph(pdb_file, amino_acid_to_index, distance_threshold=8.0):
    """Build a residue-level graph (CA atoms) from a PDB file for the GNN."""
    import torch
    from torch_geometric.data import Data
    from Bio.PDB import PDBParser
    from scipy.spatial import distance_matrix

    parser = PDBParser(QUIET=True)
    structure = parser.get_structure("protein", pdb_file)

    coordinates = []
    residue_features = []

    for model in structure:
        for chain in model:
            for residue in chain:
                if "CA" in residue:
                    coordinates.append(residue["CA"].coord)
                    residue_name = residue.get_resname()
                    feature = np.zeros(len(amino_acid_to_index))
                    if residue_name in amino_acid_to_index:
                        feature[amino_acid_to_index[residue_name]] = 1
                    residue_features.append(feature)

    if len(coordinates) == 0:
        return None

    coordinates = np.array(coordinates)
    residue_features = np.array(residue_features)
    distances = distance_matrix(coordinates, coordinates)

    edge_index = []
    for i in range(len(coordinates)):
        for j in range(len(coordinates)):
            if i != j and distances[i, j] <= distance_threshold:
                edge_index.append([i, j])

    edge_index = torch.tensor(edge_index, dtype=torch.long).t().contiguous()
    x = torch.tensor(residue_features, dtype=torch.float)

    return Data(x=x, edge_index=edge_index)


class DrugTargetGNN_Stage07:
    """Factory kept as a plain function-builder to avoid importing torch at
    module import time (torch is only required when stage 07/08/10 run)."""

    @staticmethod
    def build(node_features=20, drug_features=1024, hidden_dim=128, num_classes=2):
        import torch.nn as nn
        import torch.nn.functional as F
        from torch_geometric.nn import GCNConv, global_mean_pool

        class DrugTargetGNN(nn.Module):
            def __init__(self):
                super().__init__()
                self.conv1 = GCNConv(node_features, hidden_dim)
                self.conv2 = GCNConv(hidden_dim, hidden_dim)
                self.drug_layer = nn.Linear(drug_features, hidden_dim)
                self.classifier = nn.Sequential(
                    nn.Linear(hidden_dim * 2, hidden_dim),
                    nn.ReLU(),
                    nn.Dropout(0.3),
                    nn.Linear(hidden_dim, num_classes),
                )

            def forward(self, x, edge_index, batch, drug_features_in):
                x = self.conv1(x, edge_index)
                x = F.relu(x)
                x = self.conv2(x, edge_index)
                x = F.relu(x)
                x = global_mean_pool(x, batch)
                drug_features_in = drug_features_in.view(x.size(0), -1)
                drug_embedding = self.drug_layer(drug_features_in)
                drug_embedding = F.relu(drug_embedding)
                combined_features = __import__("torch").cat([x, drug_embedding], dim=1)
                return self.classifier(combined_features)

        return DrugTargetGNN()


