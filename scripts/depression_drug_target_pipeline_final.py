        sections = re.split(
            r"(?=Pocket\s+\d+)",
            content,
        )

        patterns = {
            "Score": (r"Score\s*:\s*" r"([-+]?\d*\.?\d+)"),
            "Druggability Score": (r"Druggability Score\s*:\s*" r"([-+]?\d*\.?\d+)"),
            "Number of Alpha Spheres": (r"Number of Alpha Spheres\s*:\s*" r"([-+]?\d*\.?\d+)"),
            "Total SASA": (r"Total SASA\s*:\s*" r"([-+]?\d*\.?\d+)"),
            "Volume": (r"Volume\s*:\s*" r"([-+]?\d*\.?\d+)"),
            "Mean local hydrophobic density": (
                r"Mean local hydrophobic density\s*:\s*" r"([-+]?\d*\.?\d+)"
            ),
            "Mean alpha sphere radius": (r"Mean alpha sphere radius\s*:\s*" r"([-+]?\d*\.?\d+)"),
        }

        for section in sections:

            match = re.search(
                r"Pocket\s+(\d+)",
                section,
            )

            if not match:
                continue

            record = {
                "rank": rank,
                "uniprot_id": protein_id,
                "drug_chembl_id": drug_id,
                "pocket_number": int(match.group(1)),
            }

            for column, pattern in patterns.items():

                value = re.search(
                    pattern,
                    section,
                    flags=re.IGNORECASE,
                )

                record[column] = float(value.group(1)) if value else np.nan

            records.append(record)

        return records

